#!/usr/bin/env node
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { buildEvidenceStatus } from './echo-evidence-status.mjs';

export const FIELD_RUN_PREP_REPORT_PATH = 'docs/evidence-drafts/project-echo-field-run-prep-report.draft.md';

export const FIELD_RUN_PREP_STEPS = [
  {
    label: 'ECHO app verify, build, bundle check, and package',
    args: ['--prefix', 'even-app', 'run', 'verify'],
  },
  {
    label: 'Project ECHO draft evidence refresh',
    args: ['run', 'prepare:echo-evidence-drafts'],
  },
  {
    label: 'Project ECHO workspace package/draft SHA check',
    args: ['run', 'validate:echo-evidence-drafts'],
  },
  {
    label: 'Project ECHO evidence status review',
    args: ['run', 'status:echo-evidence', '--', '--validate-final'],
  },
];

function npmInvocation(args) {
  if (process.platform === 'win32') {
    return {
      command: 'cmd.exe',
      args: ['/d', '/s', '/c', 'npm', ...args],
    };
  }

  return {
    command: 'npm',
    args,
  };
}

function runStep(step) {
  return new Promise((resolve, reject) => {
    console.info(`\n[echo-field-run] ${step.label}`);
    const invocation = npmInvocation(step.args);
    const child = spawn(invocation.command, invocation.args, {
      stdio: 'inherit',
      shell: false,
    });

    child.on('error', reject);
    child.on('exit', (code) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`${step.label} failed with exit code ${code}`));
    });
  });
}

export async function runFieldRunPrep(steps = FIELD_RUN_PREP_STEPS, options = {}) {
  const reportPath = options.reportPath ?? FIELD_RUN_PREP_REPORT_PATH;

  for (const [index, step] of steps.entries()) {
    await runStep(step);
    if (reportPath && step.args.join(' ') === 'run prepare:echo-evidence-drafts') {
      writeCurrentFieldRunPrepReport(reportPath, { steps, completedStepCount: index + 1 });
    }
  }

  if (reportPath) {
    writeCurrentFieldRunPrepReport(reportPath, { steps });
  }

  console.info('\n[echo-field-run] local package and draft evidence are ready for external field capture.');
  console.info('[echo-field-run] npm run readiness:echo remains the release gate and will stay blocked until final external evidence exists.');
}

export function buildFieldRunPrepReport(status, options = {}) {
  const steps = options.steps ?? FIELD_RUN_PREP_STEPS;
  const completedStepCount = options.completedStepCount ?? steps.length;
  const packageInfo = options.packageInfo ?? readPackageInfo(options.repoRoot ?? process.cwd());
  const lines = [
    '# Project ECHO Field-Run Prep Report',
    '',
    'Draft only. Generated by `npm run prepare:echo-field-run`; this report does not replace completed evidence manifests, production smoke proof, Custom GPT Action proof, portfolio links, or `npm run readiness:echo`.',
    '',
    'Local prep steps:',
    ...steps.map((step, index) => {
      const marker = index < completedStepCount ? 'PASS' : 'PENDING';
      return `- ${marker}: ${step.label} (\`${formatNpmCommand(step.args)}\`)`;
    }),
    '',
    'Package snapshot:',
    `- Package path: ${packageInfo.path}`,
    `- Package status: ${packageInfo.status}`,
  ];

  if (packageInfo.bytes != null) {
    lines.push(`- Package bytes: ${packageInfo.bytes}`);
  }
  if (packageInfo.sha256) {
    lines.push(`- Package SHA-256: ${packageInfo.sha256}`);
  }

  lines.push(
    '- Package evidence draft: docs/evidence-drafts/project-echo-build-artifact.md',
    '- Field runbook draft: docs/evidence-drafts/project-echo-field-runbook.draft.md',
    '',
    'Final evidence gates:',
  );

  for (const gate of status.finalGates) {
    lines.push(`- ${formatGateMarker(gate)} ${gate.issue}: ${gate.name} - ${gate.artifact}`);
    if (gate.validation) {
      lines.push(`  Validation: ${gate.validation.status} - ${gate.validation.detail}`);
    }
    if (gate.status !== 'present') {
      lines.push(`  Next: ${gate.next}`);
    }
    if (gate.draftRef) {
      lines.push(`  Draft support: ${gate.draftRef} (${gate.draftStatus})`);
    }
  }

  lines.push(
    '',
    'Smoke preflight:',
    `- Production proxy smoke env ready: ${status.proxySmokeEnv.ready ? 'yes' : 'no'}`,
    `- Action OAuth smoke env ready: ${status.actionOauthSmokeEnv.ready ? 'yes' : 'no'}`,
    '',
    'Draft support files:',
  );

  for (const draft of status.draftFiles) {
    const draftStatus = draft.path === FIELD_RUN_PREP_REPORT_PATH ? 'available' : draft.status;
    const marker = draftStatus === 'available' ? 'READY' : 'MISSING';
    lines.push(`- ${marker}: ${draft.name} - ${draft.path}`);
  }

  lines.push(
    '',
    'Next handoff:',
    '- Install this packaged `.ehpk` through Even Hub Private Testing or Beta Testing before final hardware QA.',
    '- Fill completed manifests only from captured external G2, proxy, Action, and pilot evidence.',
    '- Run `npm run readiness:echo` and the issue close preflight before closing any remaining issue.',
    '',
    `Summary: ${status.missingFinalCount} final gate(s) missing, ${missingDraftCountForReport(status)} draft support file(s) missing.`,
  );

  return `${lines.join('\n')}\n`;
}

function writeCurrentFieldRunPrepReport(reportPath, options) {
  const status = buildEvidenceStatus({ validateFinal: true });
  const report = buildFieldRunPrepReport(status, options);
  const writtenPath = writeFieldRunPrepReport(report, reportPath);
  console.info(`[echo-field-run] wrote ${writtenPath}`);
}

export function writeFieldRunPrepReport(markdown, reportPath, options = {}) {
  const repoRoot = path.resolve(options.repoRoot ?? process.cwd());
  const resolvedPath = resolveRepoMarkdownPath(reportPath, repoRoot);
  mkdirSync(path.dirname(resolvedPath), { recursive: true });
  writeFileSync(resolvedPath, markdown, 'utf8');
  return path.relative(repoRoot, resolvedPath).replace(/\\/g, '/');
}

function readPackageInfo(repoRoot) {
  const packagePath = 'even-app/echo.ehpk';
  const resolvedPackagePath = path.resolve(repoRoot, packagePath);
  if (!existsSync(resolvedPackagePath)) {
    return {
      path: packagePath,
      status: 'missing',
    };
  }

  const buffer = readFileSync(resolvedPackagePath);
  return {
    path: packagePath,
    status: 'available',
    bytes: statSync(resolvedPackagePath).size,
    sha256: createHash('sha256').update(buffer).digest('hex'),
  };
}

function formatNpmCommand(args) {
  return ['npm', ...args].join(' ');
}

function formatGateMarker(gate) {
  if (gate.validation?.status === 'passed') return 'VALID';
  if (gate.validation?.status === 'failed') return 'INVALID';
  if (gate.status === 'present') return 'PRESENT';
  return 'MISSING';
}

function missingDraftCountForReport(status) {
  return status.draftFiles.filter(
    (draft) => draft.path !== FIELD_RUN_PREP_REPORT_PATH && draft.status !== 'available',
  ).length;
}

function readOption(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return '';
  return process.argv[index + 1] || '';
}

function resolveRepoMarkdownPath(value, repoRoot) {
  if (!/^(?:\.{1,2}[\\/])?[A-Za-z0-9_.\-/\\]+\.md$/i.test(String(value ?? ''))) {
    throw new Error('field-run prep report path must be a repo-local markdown file');
  }

  const resolvedPath = path.resolve(repoRoot, value);
  const rootPrefix = `${repoRoot}${path.sep}`;
  if (resolvedPath !== repoRoot && !resolvedPath.startsWith(rootPrefix)) {
    throw new Error('field-run prep report path must stay inside the repository');
  }

  return resolvedPath;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await runFieldRunPrep(FIELD_RUN_PREP_STEPS, {
    reportPath: process.argv.includes('--no-report')
      ? ''
      : readOption('--out') || FIELD_RUN_PREP_REPORT_PATH,
  });
}
